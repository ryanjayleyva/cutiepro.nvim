	return {
		-- Vim syntax groups
		{ 'Comment', { fg = palette.foreground_muted } },
		{ 'Constant', { fg = palette.accent } },
		{ 'String', { fg = palette.sour_apple } },
		{ 'Character', { fg = palette.bright_blue } },
		{ 'Number', { fg = palette.bright_blue } },
		{ 'Boolean', { fg = palette.accent } },
		{ 'Float', { link = 'Number' } },
		{ 'Identifier', { fg = palette.accent } },
		{ 'Function', { fg = palette.bright_magenta } },
		{ 'Statement', { fg = palette.strawberry } },
		{ 'Conditional', { link = 'Statement' } },
		{ 'Repeat', { link = 'Statement' } },
		{ 'Label', { fg = palette.bright_cyan } },
		{ 'Operator', { fg = palette.honeycomb } },
		{ 'Exception', { fg = palette.strawberry } },
		{ 'PreProc', { fg = palette.bright_magenta } },
		{ 'Include', { link = 'PreProc' } },
		{ 'Define', { link = 'PreProc' } },
		{ 'Macro', { fg = palette.bright_cyan } },
		{ 'PreCondit', { link = 'PreProc' } },
		{ 'Type', { fg = palette.sand } },
		{ 'StorageClass', { fg = palette.strawberry } },
		{ 'Structure', { fg = palette.sand } },
		{ 'Typedef', { link = 'Type' } },
		{ 'Special', { fg = palette.bright_yellow } },
		{ 'SpecialChar', { fg = palette.bright_blue } },
		{ 'Tag', { fg = palette.strawberry } },
		{ 'Delimiter', { fg = palette.honeycomb } },
		{ 'SpecialComment', { fg = palette.foreground_muted, italic = true } },
		{ 'Underlined', { fg = palette.magenta, underline = true } },
		{ 'Error', { fg = palette.strawberry } },
		{ 'Todo', { fg = palette.accent, bold = true } },
		{ 'Added', { fg = palette.sour_apple } },
		{ 'Changed', { fg = palette.accent } },
		{ 'Removed', { fg = palette.strawberry } },

		-- Treesitter
		-- @field, @namespace and @macro are legacy capture names that older
		-- Treesitter configurations still emit, so both names are defined
		{ '@comment', { fg = palette.foreground_muted } },
		{
			'@comment.documentation',
			{ fg = palette.foreground_muted, italic = true },
		},
		{ '@comment.error', { fg = palette.strawberry, bold = true } },
		{ '@comment.warning', { fg = palette.bright_yellow, bold = true } },
		{ '@comment.note', { fg = palette.bright_blue, bold = true } },
		{ '@comment.todo', { fg = palette.accent, bold = true } },
		{ '@constant', { fg = palette.accent } },
		{ '@constant.builtin', { fg = palette.accent, italic = true } },
		{ '@constant.macro', { fg = palette.bright_cyan } },
		{ '@string', { fg = palette.sour_apple } },
		{ '@string.documentation', { fg = palette.sour_apple, italic = true } },
		{ '@string.escape', { fg = palette.bright_blue } },
		{ '@string.special', { fg = palette.bright_blue } },
		{ '@string.regexp', { fg = palette.sour_apple } },
		{ '@character', { fg = palette.bright_blue } },
		{ '@character.special', { fg = palette.bright_blue } },
		{ '@number', { fg = palette.bright_blue } },
		{ '@boolean', { fg = palette.accent } },
		{ '@number.float', { link = '@number' } },
		{ '@function', { fg = palette.bright_magenta } },
