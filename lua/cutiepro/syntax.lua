		{ '@function.method.call', { link = '@function' } },
		{ '@constructor', { fg = palette.sand } },
		{ '@variable', { fg = palette.accent } },
		{ '@variable.builtin', { fg = palette.accent, italic = true } },
		{ '@variable.parameter', { link = '@variable' } },
		{ '@variable.member', { link = '@variable' } },
		{ '@property', { link = '@variable.member' } },
		{ '@field', { link = '@variable.member' } },
		{ '@type', { fg = palette.sand } },
		{ '@type.builtin', { fg = palette.blue } },
		{ '@type.definition', { link = '@type' } },
		{ '@type.qualifier', { link = 'StorageClass' } },
		{ '@namespace', { fg = palette.sand } },
		{ '@module', { link = '@namespace' } },
		{ '@attribute', { fg = palette.bright_yellow } },
		{ '@annotation', { fg = palette.bright_yellow } },
		{ '@label', { fg = palette.bright_cyan } },
		{ '@keyword', { fg = palette.strawberry } },
		{ '@keyword.function', { link = '@keyword' } },
		{ '@keyword.return', { link = '@keyword' } },
		{ '@keyword.import', { link = '@keyword' } },
		{ '@keyword.operator', { link = '@operator' } },
		{ '@keyword.conditional', { link = '@keyword' } },
		{ '@keyword.repeat', { link = '@keyword' } },
		{ '@keyword.exception', { link = '@keyword' } },
		{ '@keyword.storage', { link = '@keyword' } },
		{ '@keyword.directive', { fg = palette.bright_magenta } },
		{ '@operator', { fg = palette.honeycomb } },
		{ '@punctuation', { fg = palette.honeycomb } },
		{ '@punctuation.delimiter', { fg = palette.honeycomb } },
		{ '@punctuation.bracket', { fg = palette.honeycomb } },
		{ '@punctuation.special', { fg = palette.honeycomb } },
		{ '@tag', { fg = palette.strawberry } },
		{ '@tag.attribute', { fg = palette.bright_yellow } },
		{ '@tag.delimiter', { fg = palette.honeycomb } },
		{ '@macro', { link = '@function.macro' } },
		{ '@symbol', { fg = palette.bright_blue } },

		-- Markup
		{ '@markup.heading', { fg = palette.accent, bold = true } },
		{ '@markup.strong', { fg = palette.foreground_bright, bold = true } },
		{ '@markup.italic', { fg = palette.bright_blue, italic = true } },
		{
			'@markup.strikethrough',
			{ fg = palette.foreground_muted, strikethrough = true },
		},
		{ '@markup.underline', { underline = true } },
		{ '@markup.quote', { fg = palette.foreground_bright, italic = true } },
		{ '@markup.raw', { fg = palette.sour_apple } },
		{ '@markup.list', { fg = palette.honeycomb } },
		{ '@markup.link', { fg = palette.magenta, underline = true } },
		{ '@markup.link.label', { fg = palette.accent } },
